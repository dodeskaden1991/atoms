window.getTarotImageUrl = function(card) {
  if (card.override && card.override.trim().length > 0) return card.override.trim();
  const base = (window.ATMOS_TAROT_IMAGE_BASE || "").trim();
  if (!base) return null;
  return base.endsWith("/") ? base + card.filename : base + "/" + card.filename;
};